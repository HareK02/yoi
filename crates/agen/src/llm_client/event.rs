//! Event types for the LLM client layer.
//!
//! Events representing streaming responses from LLM providers.

use serde::{Deserialize, Serialize};

// =============================================================================
// Core Event Types (from llm_client layer)
// =============================================================================

/// Streaming event from an LLM.
///
/// Responses from all LLM providers are handled uniformly as streams of `Event`.
///
/// # Event types
///
/// - **Meta events**: `Ping`, `Usage`, `Status`, `Error`, `UnhandledSse`
/// - **Block events**: `BlockStart`, `BlockDelta`, `BlockStop`, `BlockAbort`
///
/// # Block lifecycle
///
/// Text, thinking, and tool calls emit `BlockStart` → `BlockDelta` (multiple) →
/// `BlockStop` in order. Thinking round-trip metadata is carried in
/// `BlockStop.reasoning`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum Event {
    /// Heartbeat.
    Ping(PingEvent),
    /// Token usage.
    Usage(UsageEvent),
    /// Stream status change.
    Status(StatusEvent),
    /// Error occurred.
    Error(ErrorEvent),
    /// Unsupported SSE event that the Scheme does not interpret as generated content.
    ///
    /// An observation event for stream tracing, not reflected in the timeline or history.
    UnhandledSse(UnhandledSseEvent),

    /// Block start (text, tool use, etc.).
    BlockStart(BlockStart),
    /// Block delta data.
    BlockDelta(BlockDelta),
    /// Normal block completion.
    BlockStop(BlockStop),
    /// Block abort.
    BlockAbort(BlockAbort),
}

// =============================================================================
// Meta Events
// =============================================================================

/// Ping event (heartbeat).
#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]
pub struct PingEvent {
    pub timestamp: Option<u64>,
}

/// Usage event.
///
/// Token accounting received from the provider for one LLM request.
/// Each scheme normalizes it; field meanings are shared across providers:
///
/// - `input_tokens` is the **occupancy of the entire submitted prompt prefix**
///   (full prompt length), including cache hits. Anthropic's raw API returns only
///   uncached tokens as `input_tokens`, so `AnthropicScheme::convert_usage` adds
///   `cache_read + cache_creation` to follow this convention.
/// - `cache_read_input_tokens` / `cache_creation_input_tokens` are breakdowns
///   for billing. They are not subtracted from occupancy.
#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]
pub struct UsageEvent {
    /// Total tokens in the submitted prompt prefix (occupancy, including cached tokens).
    pub input_tokens: Option<u64>,
    /// Output tokens generated by this request.
    pub output_tokens: Option<u64>,
    /// `input_tokens + output_tokens`
    pub total_tokens: Option<u64>,
    /// Portion of `input_tokens` read from cache (discounted rate).
    pub cache_read_input_tokens: Option<u64>,
    /// Portion of `input_tokens` written to cache by this request (premium rate, Anthropic).
    pub cache_creation_input_tokens: Option<u64>,
}

/// Status event.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct StatusEvent {
    pub status: ResponseStatus,
}

/// Response status.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum ResponseStatus {
    /// Stream started.
    Started,
    /// Completed normally.
    Completed,
    /// Cancelled.
    Cancelled,
    /// Error occurred.
    Failed,
}

/// Error event.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ErrorEvent {
    pub code: Option<String>,
    pub message: String,
}

impl ErrorEvent {
    /// A provider Error event has no HTTP status. Classify its diagnostic
    /// explicitly, rather than making every status-less ClientError eligible.
    /// The engine must separately establish that no response output was seen.
    pub(crate) fn is_image_size_rejection(&self) -> bool {
        super::error::is_image_size_diagnostic(self.code.as_deref(), &self.message)
    }
}

/// Observation-only meta event for unsupported SSE events.
///
/// `data_preview` is a bounded preview of raw SSE data received from the provider;
/// `data_len` is the raw data's byte length before preview truncation.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct UnhandledSseEvent {
    pub provider: String,
    pub event_type: String,
    pub data_preview: String,
    pub data_len: usize,
}

// =============================================================================
// Block Types
// =============================================================================

/// Block type.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum BlockType {
    /// Text generation.
    Text,
    /// Thinking (e.g. Claude Extended Thinking).
    Thinking,
    /// Tool call.
    ToolUse,
    /// Tool result.
    ToolResult,
}

/// Block start event.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BlockStart {
    /// Block index.
    pub index: usize,
    /// Block type.
    pub block_type: BlockType,
    /// Block-specific metadata.
    pub metadata: BlockMetadata,
}

impl BlockStart {
    pub fn block_type(&self) -> BlockType {
        self.block_type
    }
}

/// Block metadata.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum BlockMetadata {
    Text,
    Thinking,
    ToolUse { id: String, name: String },
    ToolResult { tool_use_id: String },
}

/// Block delta event.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BlockDelta {
    /// Block index.
    pub index: usize,
    /// Delta content.
    pub delta: DeltaContent,
}

/// Delta content.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum DeltaContent {
    /// Text delta.
    Text(String),
    /// Thinking delta.
    Thinking(String),
    /// Partial JSON string for tool arguments.
    InputJson(String),
}

impl DeltaContent {
    /// Get the delta's block type.
    pub fn block_type(&self) -> BlockType {
        match self {
            DeltaContent::Text(_) => BlockType::Text,
            DeltaContent::Thinking(_) => BlockType::Thinking,
            DeltaContent::InputJson(_) => BlockType::ToolUse,
        }
    }
}

/// Block stop event.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BlockStop {
    /// Block index.
    pub index: usize,
    /// Block type.
    pub block_type: BlockType,
    /// Stop reason.
    pub stop_reason: Option<StopReason>,
    /// Reasoning round-trip metadata finalized when a Thinking block stops.
    ///
    /// Thinking blocks with `None` are for live streaming / tracing and are not
    /// persisted in history as `Item::Reasoning`. With `Some`, the block lifecycle
    /// is the authoritative source for persistence.
    pub reasoning: Option<ReasoningBlockData>,
}

impl BlockStop {
    pub fn block_type(&self) -> BlockType {
        self.block_type
    }
}

/// Block abort event.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BlockAbort {
    /// Block index.
    pub index: usize,
    /// Block type.
    pub block_type: BlockType,
    /// Abort reason.
    pub reason: String,
}

impl BlockAbort {
    pub fn block_type(&self) -> BlockType {
        self.block_type
    }
}

/// Reasoning material finalized at Thinking block stop.
///
/// Holds provider material needed to round-trip `Item::Reasoning`.
/// `text` overrides the body collected from deltas (for metadata-only reasoning
/// blocks or provider completion events that deliver the full text).
#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]
pub struct ReasoningBlockData {
    /// Item ID observed by the scheme (OpenAI Responses `id`).
    pub id: Option<String>,
    /// Reasoning body text. `None` uses the collected block deltas.
    pub text: Option<String>,
    /// Summary (OpenAI Responses `summary_text[]`); empty for other schemes.
    pub summary: Vec<String>,
    /// Encrypted opaque blob (Anthropic `redacted_thinking.data` /
    /// OpenAI Responses `encrypted_content`).
    pub encrypted_content: Option<String>,
    /// Anthropic extended thinking signature, required for round-tripping.
    pub signature: Option<String>,
}

/// Stop reason.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum StopReason {
    /// Natural end of turn.
    EndTurn,
    /// Maximum token count reached.
    MaxTokens,
    /// Stop sequence reached.
    StopSequence,
    /// Tool use.
    ToolUse,
}

// =============================================================================
// Builder / Factory helpers
// =============================================================================

impl Event {
    /// Create a text block start event.
    pub fn text_block_start(index: usize) -> Self {
        Event::BlockStart(BlockStart {
            index,
            block_type: BlockType::Text,
            metadata: BlockMetadata::Text,
        })
    }

    /// Create a text delta event.
    pub fn text_delta(index: usize, text: impl Into<String>) -> Self {
        Event::BlockDelta(BlockDelta {
            index,
            delta: DeltaContent::Text(text.into()),
        })
    }

    /// Create a text block stop event.
    pub fn text_block_stop(index: usize, stop_reason: Option<StopReason>) -> Self {
        Event::BlockStop(BlockStop {
            index,
            block_type: BlockType::Text,
            stop_reason,
            reasoning: None,
        })
    }

    /// Create a tool use block start event.
    pub fn tool_use_start(index: usize, id: impl Into<String>, name: impl Into<String>) -> Self {
        Event::BlockStart(BlockStart {
            index,
            block_type: BlockType::ToolUse,
            metadata: BlockMetadata::ToolUse {
                id: id.into(),
                name: name.into(),
            },
        })
    }

    /// Create a tool argument delta event.
    pub fn tool_input_delta(index: usize, json: impl Into<String>) -> Self {
        Event::BlockDelta(BlockDelta {
            index,
            delta: DeltaContent::InputJson(json.into()),
        })
    }

    /// Create a tool use block stop event.
    pub fn tool_use_stop(index: usize) -> Self {
        Event::BlockStop(BlockStop {
            index,
            block_type: BlockType::ToolUse,
            stop_reason: Some(StopReason::ToolUse),
            reasoning: None,
        })
    }

    /// Create a usage event.
    pub fn usage(input_tokens: u64, output_tokens: u64) -> Self {
        Event::Usage(UsageEvent {
            input_tokens: Some(input_tokens),
            output_tokens: Some(output_tokens),
            total_tokens: Some(input_tokens + output_tokens),
            cache_read_input_tokens: None,
            cache_creation_input_tokens: None,
        })
    }

    /// Create a Ping event.
    pub fn ping() -> Self {
        Event::Ping(PingEvent { timestamp: None })
    }
}

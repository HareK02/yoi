//! Per-LLM-request usage measurement snapshot.
//!
//! Records measured token usage for the history prefix included in one request.
//! The caller builds it from provider `UsageEvent`s and passes it to persistence
//! or to token accounting (`token_counter`).

/// Usage snapshot for the history prefix sent with an LLM request.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UsageRecord {
    /// `history.len()` when the request was sent.
    pub history_len: usize,
    /// Measured total prompt tokens for `history[..history_len]`.
    pub input_total_tokens: u64,
    /// Portion of the input tokens read from cache.
    pub cache_read_tokens: u64,
    /// Portion of the input tokens written to cache by this request.
    pub cache_write_tokens: u64,
    /// Output tokens generated by this request.
    pub output_tokens: u64,
}

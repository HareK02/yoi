    let response = failure(StartupCause::Boundary(StartupBoundaryCause {
        reason: StartupBoundaryReason::Timeout,
    }))
    .problem(StartupBoundary::Browser, &visible(), "")
    .unwrap();
    assert_eq!(response.status, 504);
    let mut value: Value = serde_json::from_slice(response.body()).unwrap();
    value["retry_after"] = json!(0);

//! Producer/consumer checks against the production constructor and decoder.
use error_contract::problem::ApiBoundary as _;
use error_contract::{
    Browser, ContractError, DecodeFailure, FailureCause, FailureFacts, InternalTransfer,
    OperationContext, ProjectFor, WireDetails, project_failure,
};
use protocol::session_failure::{SessionPrincipal, SessionRegistrationCause};
use runtime_api::startup::*;
use runtime_api::{
    RuntimeStartupCause, RuntimeStartupReason, StartupCleanup, StartupCleanupFailure,
    StartupFailureAttachment, StartupFailurePhase, StartupIoKind, StartupPersistenceOutcome,
    StartupResourceFacts, StartupResources, StartupSecondaryFailure, StartupStage,
    WorkerStartupFailure,
};
use serde_json::{Value, json};

fn visible() -> SessionFailureVisibility {
    SessionFailureVisibility {
        can_view_cause: true,
    }
}
fn operation(acceptance: CreationAcceptance, execution: ExecutionOutcome) -> StartupOperationFacts {
    StartupOperationFacts {
        acceptance,
        execution,
        finalize: None,
        backend_compensation: None,
        correlation: Some(StartupCorrelation::new("startup-fixture-812").unwrap()),
    }
}
fn session() -> StartupCause {
    StartupCause::Session(SessionRegistrationCause::denied(SessionPrincipal::Subject))
}
fn failure(cause: StartupCause) -> WorkerCreateFailure {
    WorkerCreateFailure::from_cause(
        cause,
        operation(CreationAcceptance::Unknown, ExecutionOutcome::Unknown),
    )
    .unwrap()
}
fn decode(value: &Value, status: u16, boundary: StartupBoundary) -> DecodeStartupProblem {
    decode_startup_problem(
        &serde_json::to_vec(value).unwrap(),
        status,
        PROBLEM_CONTENT_TYPE,
        boundary,
    )
}
fn known(result: DecodeStartupProblem) -> WorkerCreateFailure {
    match result {
        DecodeStartupProblem::Known(failure) => failure,
        other => panic!("{other:?}"),
    }
}
fn fixture_failure() -> WorkerCreateFailure {
    let base = failure(session());
    let (mut startup, _) = base.into_parts();
    startup.secondary = vec![
        StartupSecondaryFailure::Cleanup {
            failure: StartupCleanupFailure::Workdir,
        },
        StartupSecondaryFailure::Persistence {
            phase: StartupFailurePhase::MetadataSave,
            outcome: StartupPersistenceOutcome::OutcomeUnknown,
        },
    ];
    startup.resources = Some(StartupResourceFacts {
        resources: StartupResources::WorkerStartup,
        cleanup: StartupCleanup::Failed(StartupCleanupFailure::Workdir),
        durable_effects_possible: true,
    });
    startup.persistence = Some(StartupPersistenceOutcome::OutcomeUnknown);
    startup.io_kind = Some(StartupIoKind::PermissionDenied);
    WorkerCreateFailure::new(
        startup,
        operation(CreationAcceptance::Rejected, ExecutionOutcome::Rejected),
    )
    .unwrap()
}

#[test]
fn production_public_fixture_is_stable_and_consumable() {
    let failure = fixture_failure();
    let response = failure
        .problem(
            StartupBoundary::Browser,
            &visible(),
            "/workers/create/fixture-812",
        )
        .unwrap();
    assert_eq!(response.status, 409);
    assert_eq!(response.content_type, PROBLEM_CONTENT_TYPE);
    let value: Value = serde_json::from_slice(response.body()).unwrap();
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/startup-session-record-denied.problem.json");
    let fixture: Value = serde_json::from_slice(&std::fs::read(path).unwrap()).unwrap();
    assert_eq!(
        value, fixture,
        "fixture must be generated by the public production constructor"
    );
    let decoded = known(decode(&fixture, 409, StartupBoundary::Browser));
    assert_eq!(decoded.operation(), failure.operation());
    assert_eq!(decoded.public_facts(), failure.public_facts());
    assert_eq!(
        decoded
            .startup()
            .primary
            .decode::<StartupCause>()
            .known_cause(),
        session()
    );
    assert!(fixture["detail"].as_str().unwrap().contains("Subject"));
    assert!(
        fixture["detail"]
            .as_str()
            .unwrap()
            .contains("session.record")
    );
    assert!(fixture["detail"].as_str().unwrap().contains("Worker"));
    assert!(fixture["yoi_startup"].get("primary").is_none());
}

/// Captured from the real signed Session registration → Runtime → Browser tests
/// in workspace-server. These are observed operation facts, not a declaration
/// that an HTTP conflict rejected creation or that successful cleanup erased effects.
#[test]
fn connected_browser_fixtures_preserve_observed_operation_and_storage_facts() {
    for (body, status, cause) in [
        (
            include_bytes!("fixtures/startup-browser-session-record-denied.problem.json")
                .as_slice(),
            409,
            SessionRegistrationCause::denied(SessionPrincipal::Subject),
        ),
        (
            include_bytes!("fixtures/startup-browser-registration-response-lost.problem.json")
                .as_slice(),
            502,
            SessionRegistrationCause::outcome_unknown(),
        ),
    ] {
        let failure = known(decode_startup_problem(
            body,
            status,
            PROBLEM_CONTENT_TYPE,
            StartupBoundary::Browser,
        ));
        assert_eq!(
            failure
                .startup()
                .primary
                .decode::<StartupCause>()
                .known_cause(),
            StartupCause::Session(cause)
        );
        assert_eq!(failure.operation().acceptance, CreationAcceptance::Unknown);
        assert_eq!(failure.operation().execution, ExecutionOutcome::Errored);
        assert_eq!(
            failure.operation().backend_compensation,
            Some(CompensationOutcome::Unknown)
        );
        assert_eq!(
            failure.startup().persistence,
            Some(StartupPersistenceOutcome::Persisted)
        );
        assert_eq!(
            failure.backend_result_persistence(),
            Some(StartupPersistenceOutcome::Persisted)
        );
        let encoded = failure.encode_storage().unwrap();
        let DecodeStoredWorkerCreateFailure::Known(saved) =
            decode_stored_worker_create_failure(&encoded)
        else {
            panic!("connected result must survive HTTP-independent storage");
        };
        assert_eq!(saved.public_facts(), failure.public_facts());
        let response = saved
            .problem(StartupBoundary::Browser, &visible(), "")
            .unwrap();
        assert_eq!(response.status, status);
        let original: Value = serde_json::from_slice(body).unwrap();
        let projected: Value = serde_json::from_slice(response.body()).unwrap();
        assert_eq!(projected["detail"], original["detail"]);
        assert_eq!(projected["yoi_startup"], original["yoi_startup"]);
    }
}

// A tiny test-only adapter so assertions never format raw received data.
trait CauseFromDecode {
    fn known_cause(self) -> StartupCause;
}
impl CauseFromDecode for DecodeFailure<StartupCause> {
    fn known_cause(self) -> StartupCause {
        match self {
            DecodeFailure::Known(received) => received.facts().cause().clone(),
            _ => panic!("expected known cause"),
        }
    }
}


#[test]
fn telemetry_uses_typed_context_and_operation_correlation_not_attachment_identity() {
    use error_contract::{CorrelationRef, Telemetry, observation_fields};
    let mut facts = FailureFacts::new(session()).unwrap();
    let mut context = OperationContext::new("session.record", "registration").unwrap();
    context.operation_ref = Some("PRIVATE_OPERATION_ID".into());
    facts.with_context(context).unwrap();
    facts
        .with_context(OperationContext::new("SECRET_CONTEXT", "SECRET_STAGE").unwrap())
        .unwrap();
    facts
        .set_correlation(CorrelationRef::new("UNTRUSTED_ATTACHMENT_ID").unwrap())
        .unwrap();
    let projected = project_failure::<Telemetry, _>(&facts, &()).unwrap();
    let fields = observation_fields(&projected);
    assert_eq!(fields.domain, "session_registration");
    assert_eq!(fields.reason, "permission_denied");
    assert_eq!(fields.operation, Some("worker_startup"));
    assert_eq!(fields.stage, Some("binding"));
    assert_eq!(fields.correlation, Some("UNTRUSTED_ATTACHMENT_ID"));
    assert!(
        projected
            .context()
            .operations
            .iter()
            .all(|op| op.operation_ref.is_none())
    );

    let transfer = project_failure::<InternalTransfer, _>(&facts, &()).unwrap();
    let startup = WorkerStartupFailure {
        primary: StartupFailureAttachment::from_projected(&transfer).unwrap(),
        secondary: vec![],
        resources: None,
        persistence: None,
        io_kind: None,
    };
    let mut operation = operation(CreationAcceptance::Unknown, ExecutionOutcome::Unknown);
    operation.correlation = Some(StartupCorrelation::new("fresh-backend-correlation").unwrap());
    let failure = WorkerCreateFailure::new(startup, operation).unwrap();
    let telemetry = failure.telemetry().unwrap();
    assert_eq!(
        observation_fields(&telemetry).correlation,
        Some("fresh-backend-correlation")
    );
    assert_eq!(telemetry.identity(), session().identity());
    let encoded = error_contract::encode_projected_failure(
        &telemetry,
        error_contract::Budget::new(32768, 32768),
    )
    .unwrap();
    let text = std::str::from_utf8(encoded.as_bytes()).unwrap();
    for secret in [
        "PRIVATE_OPERATION_ID",
        "SECRET_CONTEXT",
        "SECRET_STAGE",
        "UNTRUSTED_ATTACHMENT_ID",
    ] {
        assert!(!text.contains(secret));
    }
    let (startup, mut operation) = failure.into_parts();
    operation.correlation = None;
    assert_eq!(
        observation_fields(
            &WorkerCreateFailure::new(startup, operation)
                .unwrap()
                .telemetry()
                .unwrap()
        )
        .correlation,
        None
    );
}


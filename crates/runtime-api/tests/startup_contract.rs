#[test]
fn unknown_version_reason_and_bad_envelopes_are_distinct() {
    let response = fixture_failure()
        .problem(StartupBoundary::Browser, &visible(), "")
        .unwrap();
    let original: Value = serde_json::from_slice(response.body()).unwrap();
    for field in ["version", "details_version"] {
        let mut value = original.clone();
        value["yoi_failure"][field] = json!(77);
        assert_eq!(
            decode(&value, 409, StartupBoundary::Browser),
            DecodeStartupProblem::UnsupportedVersion
        );
    }
    let mut value = original.clone();
    value["yoi_startup"]["version"] = json!(77);
    assert_eq!(
        decode(&value, 409, StartupBoundary::Browser),
        DecodeStartupProblem::UnsupportedVersion
    );
    value = original.clone();
    value["yoi_failure"]["required_extensions"] = json!(["future-contract"]);
    assert_eq!(
        decode(&value, 409, StartupBoundary::Browser),
        DecodeStartupProblem::UnsupportedVersion
    );
    value = original.clone();
    value["yoi_failure"]["reason"] = json!("future_reason");
    value["yoi_failure"]["category"] = json!("future_category");
    assert_eq!(
        decode(&value, 409, StartupBoundary::Browser),
        DecodeStartupProblem::UnsupportedReason
    );
    value = original.clone();
    value["yoi_failure"]["domain"] = json!("future_domain");
    assert_eq!(
        decode(&value, 409, StartupBoundary::Browser),
        DecodeStartupProblem::UnsupportedReason
    );
    for mutate in ["category", "domain", "reason"] {
        let mut value = original.clone();
        // Another KNOWN identity with mismatching typed details must be invalid.
        value["yoi_failure"][mutate] = match mutate {
            "category" => json!("internal"),
            "domain" => json!("startup_boundary"),
            _ => json!("transport"),
        };
        let result = decode(&value, 409, StartupBoundary::Browser);
        if mutate != "domain" {
            assert_eq!(result, DecodeStartupProblem::Invalid);
        } else {
            assert_eq!(result, DecodeStartupProblem::UnsupportedReason);
        }
    }
    for field in ["version", "details_version"] {
        let mut value = original.clone();
        value["yoi_failure"][field] = json!(0);
        assert_eq!(
            decode(&value, 409, StartupBoundary::Browser),
            DecodeStartupProblem::Invalid
        );
    }
}

#[test]
fn decoder_rejects_incoherence_bad_shapes_duplicate_fields_and_limits() {
    let response = failure(session())
        .problem(StartupBoundary::Browser, &visible(), "")
        .unwrap();
    let original: Value = serde_json::from_slice(response.body()).unwrap();
    assert_eq!(
        decode_startup_problem(
            response.body(),
            403,
            PROBLEM_CONTENT_TYPE,
            StartupBoundary::Browser
        ),
        DecodeStartupProblem::Invalid
    );
    assert_eq!(
        decode_startup_problem(
            response.body(),
            409,
            "application/json",
            StartupBoundary::Browser
        ),
        DecodeStartupProblem::Invalid
    );
    assert!(matches!(
        decode_startup_problem(
            response.body(),
            409,
            "Application/Problem+Json; charset=utf-8",
            StartupBoundary::Browser
        ),
        DecodeStartupProblem::Known(_)
    ));
    assert_eq!(
        decode_startup_problem(
            response.body(),
            409,
            PROBLEM_CONTENT_TYPE,
            StartupBoundary::Runtime
        ),
        DecodeStartupProblem::Invalid
    );
    for (field, replacement) in [
        ("status", json!(502)),
        ("type", json!("urn:wrong")),
        ("title", json!("raw upstream")),
        ("detail", json!("different")),
        ("instance", json!("%zz")),
    ] {
        let mut value = original.clone();
        value[field] = replacement;
        assert_eq!(
            decode(&value, 409, StartupBoundary::Browser),
            DecodeStartupProblem::Invalid
        );
    }
    for field in ["yoi_failure", "yoi_startup"] {
        let mut value = original.clone();
        value.as_object_mut().unwrap().remove(field);
        assert_eq!(
            decode(&value, 409, StartupBoundary::Browser),
            DecodeStartupProblem::Invalid
        );
    }
    let text = std::str::from_utf8(response.body()).unwrap();
    for (needle, duplicated) in [
        ("\"status\":409", "\"status\":409,\"status\":409"),
        (
            "\"acceptance\":\"unknown\"",
            "\"acceptance\":\"unknown\",\"acceptance\":\"rejected\"",
        ),
        (
            "\"principal\":\"subject\"",
            "\"principal\":\"subject\",\"principal\":\"operator\"",
        ),
    ] {
        let duplicate = text.replace(needle, duplicated);
        assert_ne!(duplicate, text);
        assert_eq!(
            decode_startup_problem(
                duplicate.as_bytes(),
                409,
                PROBLEM_CONTENT_TYPE,
                StartupBoundary::Browser
            ),
            DecodeStartupProblem::Invalid
        );
    }
    let oversized = vec![b' '; MAX_STARTUP_PROBLEM_BYTES + 1];
    assert_eq!(
        decode_startup_problem(
            &oversized,
            409,
            PROBLEM_CONTENT_TYPE,
            StartupBoundary::Browser
        ),
        DecodeStartupProblem::TooLarge
    );
    let deep = format!("{}0{}", "[".repeat(1000), "]".repeat(1000));
    assert_eq!(
        decode_startup_problem(
            deep.as_bytes(),
            409,
            PROBLEM_CONTENT_TYPE,
            StartupBoundary::Browser
        ),
        DecodeStartupProblem::Invalid
    );
    for bytes in [b"not json".as_slice(), b"\xff".as_slice(), b"{}".as_slice()] {
        assert_eq!(
            decode_startup_problem(bytes, 409, PROBLEM_CONTENT_TYPE, StartupBoundary::Browser),
            DecodeStartupProblem::Invalid
        );
    }
}


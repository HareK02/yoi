fn validate_contract_digest(digest: &str) -> Result<(), GenerationError> {
    let Some(hex) = digest.strip_prefix("sha256:") else {
        return Err(GenerationError::invalid(
            "OpenAPI source digest must use sha256",
        ));
    };
    if hex.len() != 64 || !hex.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        return Err(GenerationError::invalid(
            "OpenAPI source digest must contain 64 hexadecimal digits",
        ));
    }
    Ok(())
}


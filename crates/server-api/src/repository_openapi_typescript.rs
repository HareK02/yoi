const SCHEMA_REF_PREFIX: &str = "#/components/schemas/";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GenerationError(String);

impl GenerationError {
    fn invalid(message: impl Into<String>) -> Self {
        Self(message.into())
    }
}

impl std::fmt::Display for GenerationError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(&self.0)
    }
}

impl std::error::Error for GenerationError {}

pub fn generate_repository_typescript(input: &str) -> Result<String, GenerationError> {
    let document: Value = serde_json::from_str(input)
        .map_err(|error| GenerationError::invalid(format!("invalid OpenAPI JSON: {error}")))?;
    let root = object(&document, "OpenAPI document")?;
    if root.get("openapi").and_then(Value::as_str) != Some("3.1.0") {
        return Err(GenerationError::invalid(
            "Repository TypeScript generation requires OpenAPI 3.1.0",
        ));
    }

    let info = object_field(root, "info", "OpenAPI document")?;
    let contract_version = required_string(info, "version", "OpenAPI info")?;
    let contract_digest = required_string(info, "x-yoi-source-digest", "OpenAPI info")?;
    validate_contract_digest(contract_digest)?;

    let schemas = object_field(
        object_field(root, "components", "OpenAPI document")?,
        "schemas",
        "OpenAPI components",
    )?;
    let paths = object_field(root, "paths", "OpenAPI document")?;
    let roots = validate_repository_operations(paths)?;
    let closure = schema_closure(schemas, &roots)?;

    let mut output = format!(
        "// @generated by {GENERATOR_NAME}@{GENERATOR_VERSION}. Do not edit.\n\
// Input: {INPUT_PATH}\n\
// Input contract: {contract_version} ({contract_digest})\n\
// Options: {GENERATOR_OPTIONS}\n\
// Output: {OUTPUT_PATH}\n\
// Regenerate/check: cargo run -q -p server-api --example generate_repository_openapi_types -- --check\n\n"
    );
    for name in closure {
        let schema = schemas
            .get(&name)
            .ok_or_else(|| GenerationError::invalid(format!("missing schema `{name}`")))?;
        let declaration = render_schema(schema, &format!("schema `{name}`"))?;
        output.push_str(&format!("export type {name} = {declaration};\n\n"));
    }
    output.pop();
    Ok(output)
}


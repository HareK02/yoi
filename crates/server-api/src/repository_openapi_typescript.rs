fn validate_runtime_operation_contracts(
    paths: &Map<String, Value>,
    operations: &[RuntimeOperationContract],
) -> Result<BTreeSet<String>, GenerationError> {
    let mut roots = BTreeSet::new();
    for operation in operations {
        let path = object_field(paths, operation.path, "OpenAPI paths")?;
        let value = object_field(path, operation.method, operation.path)?;
        if value.get("operationId").and_then(Value::as_str) != Some(operation.operation_id) {
            return Err(GenerationError::invalid(format!(
                "{} {} must retain operationId `{}`",
                operation.method, operation.path, operation.operation_id
            )));
        }
        if operation.binary_request {
            let request = object_field(value, "requestBody", operation.operation_id)?;
            validate_binary_request_body(request, operation.operation_id)?;
        } else {
            match operation.request {
                Some(expected) => {
                    let request = object_field(value, "requestBody", operation.operation_id)?;
                    require_schema_ref(
                        json_content_schema(request, operation.operation_id)?,
                        expected,
                        operation.operation_id,
                    )?;
                    roots.insert(expected.to_owned());
                }
                None if value.contains_key("requestBody") => {
                    return Err(GenerationError::invalid(format!(
                        "{} unexpectedly gained a request body",
                        operation.operation_id
                    )));
                }
                None => {}
            }
        }
        let responses = object_field(value, "responses", operation.operation_id)?;
        let successes = operation
            .successes
            .iter()
            .copied()
            .collect::<BTreeMap<_, _>>();
        for (status, response) in responses {
            let response = object(
                response,
                &format!("{} response {status}", operation.operation_id),
            )?;
            let expected = successes
                .get(status.as_str())
                .copied()
                .unwrap_or(operation.error);
            require_schema_ref(
                json_content_schema(response, operation.operation_id)?,
                expected,
                operation.operation_id,
            )?;
            roots.insert(expected.to_owned());
        }
        for (status, expected) in successes {
            if !responses.contains_key(status) {
                return Err(GenerationError::invalid(format!(
                    "{} is missing success response {status} ({expected})",
                    operation.operation_id
                )));
            }
        }
    }
    Ok(roots)
}


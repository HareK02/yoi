//! Subject-facing projections and intents over ordinary Worker lifecycle authority.
//! No current-body mapping or execution state is owned by these DTOs.
use crate::{Diagnostic, WorkerSummary};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
#[serde(deny_unknown_fields)]
pub struct SubjectBodyRef {
    pub runtime_id: String,
    pub worker_id: String,
    /// Decimal text preserves the full singleton generation through browsers.
    pub generation: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
#[serde(tag = "kind", rename_all = "snake_case", deny_unknown_fields)]
pub enum SubjectBodyObservation {
    Absent,
    Available {
        worker: WorkerSummary,
    },
    /// The owner is still occupied; this must not invite a replacement launch.
    Unavailable {
        diagnostics: Vec<Diagnostic>,
    },
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
#[serde(deny_unknown_fields)]
pub struct SubjectBodyResponse {
    pub workspace_id: String,
    pub subject_id: String,
    pub current: Option<SubjectBodyRef>,
    pub observation: SubjectBodyObservation,
    /// Account authority, not a claim that Profile/model/Runtime admission will succeed.
    pub can_start: bool,
    pub can_stop: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
#[serde(deny_unknown_fields)]
pub struct SubjectBodyStartRequest {
    pub request_id: String,
    /// Null explicitly means the caller observed no owner, not an unspecified target.
    #[serde(deserialize_with = "required_nullable_current")]
    #[schemars(required)]
    pub expected_current: Option<SubjectBodyRef>,
    pub expected_observation_token: Option<String>,
}

fn required_nullable_current<'de, D: serde::Deserializer<'de>>(
    deserializer: D,
) -> Result<Option<SubjectBodyRef>, D::Error> {
    Option::<SubjectBodyRef>::deserialize(deserializer)
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
#[serde(deny_unknown_fields)]
pub struct SubjectBodyStopRequest {
    pub request_id: String,
    pub expected_current: SubjectBodyRef,
    pub expected_observation_token: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
#[serde(rename_all = "snake_case")]
pub enum SubjectBodyDisposition {
    Accepted,
    Rejected,
    Unknown,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
#[serde(deny_unknown_fields)]
pub struct SubjectBodyMutationResponse {
    pub request_id: String,
    pub disposition: SubjectBodyDisposition,
    pub diagnostics: Vec<Diagnostic>,
    /// Fresh observation is independent of the historical operation receipt.
    pub body: Option<SubjectBodyResponse>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
#[serde(rename_all = "snake_case")]
pub enum SubjectBodyStopOutcome {
    NotFound,
    Pending,
    Stopped,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
#[serde(deny_unknown_fields)]
pub struct SubjectBodyStopOutcomeResponse {
    pub request_id: String,
    /// Historical operation evidence, never the current body's running state.
    pub outcome: SubjectBodyStopOutcome,
    pub body: Option<SubjectBodyResponse>,
}

#[cfg(feature = "typescript")]
pub fn subject_body_api_typescript() -> String {
    use ts_rs::TS;
    let config = ts_rs::Config::default();
    let declarations = [
        SubjectBodyRef::decl(&config),
        SubjectBodyObservation::decl(&config),
        SubjectBodyResponse::decl(&config),
        SubjectBodyStartRequest::decl(&config),
        SubjectBodyStopRequest::decl(&config),
        SubjectBodyDisposition::decl(&config),
        SubjectBodyMutationResponse::decl(&config),
        SubjectBodyStopOutcome::decl(&config),
        SubjectBodyStopOutcomeResponse::decl(&config),
    ];
    format!(
        "// Generated by `cargo run -p server-api --features typescript --example generate_subject_body_api_types`.\n// Do not edit manually.\n\nimport type {{ Diagnostic, WorkerSummary }} from \"./worker-launch-api\";\n\n{}\n",
        declarations
            .into_iter()
            .map(|declaration| format!("export {declaration}"))
            .collect::<Vec<_>>()
            .join("\n\n")
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn start_requires_an_explicit_nullable_current_observation() {
        assert!(
            serde_json::from_value::<SubjectBodyStartRequest>(json!({"request_id":"start"}))
                .is_err()
        );
        let request: SubjectBodyStartRequest = serde_json::from_value(json!({"request_id":"start", "expected_current":null, "expected_observation_token":null})).unwrap();
        assert!(request.expected_current.is_none());
    }

    #[cfg(feature = "typescript")]
    #[test]
    fn generated_subject_body_contract_is_current() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../web/workspace/src/lib/generated/subject-body-api.ts");
        let actual = std::fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("failed to read {}: {error}", path.display()));
        let normalize = |value: &str| {
            value
                .chars()
                .filter_map(|character| match character {
                    character if character.is_whitespace() => None,
                    ',' => Some(';'),
                    character => Some(character),
                })
                .collect::<String>()
                .replace("=|", "=")
                .replace(";}", "}")
        };
        assert_eq!(
            normalize(&actual),
            normalize(&subject_body_api_typescript()),
            "regenerate subject-body-api.ts using generate_subject_body_api_types and format the result"
        );
    }

    #[test]
    fn stop_intent_requires_target_and_observation() {
        let valid = json!({
            "request_id": "stop-1",
            "expected_current": {"runtime_id":"runtime", "worker_id":"worker", "generation":"18446744073709551615"},
            "expected_observation_token":"observed"
        });
        let request: SubjectBodyStopRequest = serde_json::from_value(valid.clone()).unwrap();
        assert_eq!(request.expected_current.generation, "18446744073709551615");
        for field in [
            "expected_current",
            "expected_observation_token",
            "request_id",
        ] {
            let mut missing = valid.clone();
            missing.as_object_mut().unwrap().remove(field);
            assert!(serde_json::from_value::<SubjectBodyStopRequest>(missing).is_err());
        }
    }
}
